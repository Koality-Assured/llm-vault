function getRandomInt(max: number): number {
  if (max <= 0) return 0;
  const array = new Uint32Array(1);
  const range = 0x100000000;
  const limit = range - (range % max);
  let value: number;
  do {
    crypto.getRandomValues(array);
    value = array[0]!;
  } while (value >= limit);
  return value % max;
}

export function generatePassword(options: PasswordGeneratorOptions): string {
  const length = Math.max(8, Math.min(128, options.length));
  let charPool = "";
  const guaranteedChars: string[] = [];

  const upper = options.excludeAmbiguous ? UPPERCASE_CHARS : UPPERCASE_FULL;
  const lower = options.excludeAmbiguous ? LOWERCASE_CHARS : LOWERCASE_FULL;
  const nums = options.excludeAmbiguous ? NUMBER_CHARS : NUMBER_FULL;

  if (options.includeUppercase) {
    charPool += upper;
    guaranteedChars.push(upper[getRandomInt(upper.length)]!);
  }
  if (options.includeLowercase) {
    charPool += lower;
    guaranteedChars.push(lower[getRandomInt(lower.length)]!);
  }
  if (options.includeNumbers) {
    charPool += nums;
    guaranteedChars.push(nums[getRandomInt(nums.length)]!);
  }
  if (options.includeSymbols) {
    charPool += SYMBOL_CHARS;
    guaranteedChars.push(SYMBOL_CHARS[getRandomInt(SYMBOL_CHARS.length)]!);
  }

  // Fallback if no sets selected
  if (!charPool) {
    charPool = lower + nums;
  }

  const result: string[] = [...guaranteedChars];
  while (result.length < length) {
    result.push(charPool[getRandomInt(charPool.length)]!);
  }

  // Fisher-Yates shuffle using cryptographically random swaps
  for (let i = result.length - 1; i > 0; i--) {
    const j = getRandomInt(i + 1);
    const temp = result[i]!;
    result[i] = result[j]!;
    result[j] = temp;
  }

  return result.join("");
}

export function generatePassphrase(options: PassphraseGeneratorOptions): string {
  const wordCount = Math.max(3, Math.min(12, options.wordCount));
  const words: string[] = [];

  for (let i = 0; i < wordCount; i++) {
    let word = WORDLIST[getRandomInt(WORDLIST.length)]!;
    if (options.capitalize) {
      word = word.charAt(0).toUpperCase() + word.slice(1);
    }
    words.push(word);
  }

  if (options.includeNumber) {
    const randomDigit = getRandomInt(10);
    const pos = getRandomInt(words.length);
    words[pos] = `${words[pos]}${randomDigit}`;
  }

  return words.join(options.delimiter);
}

export function estimateEntropyBits(secret: string): number {
  if (!secret) return 0;
  let poolSize = 0;
  if (/[a-z]/.test(secret)) poolSize += 26;
  if (/[A-Z]/.test(secret)) poolSize += 26;
  if (/[0-9]/.test(secret)) poolSize += 10;
  if (/[^a-zA-Z0-9]/.test(secret)) poolSize += 32;

  if (poolSize === 0) poolSize = 1;
  return Math.round(secret.length * Math.log2(poolSize));
}
